package com.aboveware.aboveabc80

internal data class ABC80KeyCodes(
    val unshifted: Int,
    val shifted: Int,
    val controlled: Int,
    val shiftControlled: Int
) {
    fun code(shift: Boolean, control: Boolean): Int = when {
        shift && control -> shiftControlled
        control -> controlled
        shift -> shifted
        else -> unshifted
    }
}

