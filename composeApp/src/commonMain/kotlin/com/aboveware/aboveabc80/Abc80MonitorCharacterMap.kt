    fun forEach(char: Int, action: (UByte, Int) -> Unit) {
        for (row in 0 until charHeight) {
            action(character(char, row), row)
        }
    }

    @ExperimentalUnsignedTypes
    fun forEachBit(char: Int, action: (Boolean, Int) -> Unit) {
        for (col in 0 until charWidth) {
            action(char shl col and 128 == 128, col)
