    // Shared Paper Buffer: 0=None, 1=Black, 2=Red
    val lines = mutableStateListOf<IntArray>()
    var isVisible by mutableStateOf(value = false)

    private fun getDriver(): Printer {
        return when (PrinterManager.currentPrinterType) {
            PrinterType.EPSON_MX80 -> MX80.instance
            PrinterType.EPSON_FX80 -> FX80.instance
            PrinterType.DIABLO_630 -> Diablo630.instance
        }
    }

    fun printChar(c: Char) {
        if (!isVisible) {
            Abc80Log.terminal("VirtualPrinter: Becoming visible due to printChar('${if (c.code >= 32) c else '.'}')")
            isVisible = true
        }
        getDriver().printChar(c)
    }

    val activeTestData: List<String>
        get() = getDriver().testData

    fun formFeed() {
        getDriver().reset()
        lines.clear()
    }

    fun clear() {
        formFeed()
        isVisible = false
    }

    fun syncDriver() {
        getDriver().syncWithDipSwitches()
    }
